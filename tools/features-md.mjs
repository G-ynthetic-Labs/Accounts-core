/**
 * The readable feature list, `features.md`: each feature with what it covers, the files that carry it (with their
 * one-line descriptions and line counts) and the addresses it holds, written from the same data as `feature-map.json`.
 *
 * Spec: POL-CODE-004 (feature map) · owner 21 Nov 2026 ("a features.md and a codemap.json")
 * Source of truth: repo.json → features and x-featureNotes; the file headers
 * @feature accounts-tools
 */
/*
 * How it works. `featuresMarkdown` takes repo.json, the sorted feature map and the per-file maps, and returns the
 * Markdown text, headed by the legal notice. Nothing is read or written here; tools/code-map.mjs writes the file and checks it is current.
 */

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');

/** The Markdown text of features.md. */
export function featuresMarkdown(repo, features, maps) {
  const notes = repo['x-featureNotes'] ?? {};
  const out = [
    `<!-- Copyright (c) 2026 ${repo.ownerLegalName}. All rights reserved. -->`,
    `<!-- Proprietary and confidential. Trade secret of ${repo.ownerLegalName}. Unauthorized copying, use or disclosure is prohibited. See LICENSE. -->`,
    `# Features · ${repo.title}`,
    '',
    'Generated by `npm run map` from the file headers (`@feature`, `@address`). Do not edit by hand; the machine-readable',
    'twin is `feature-map.json`, and every file is mapped in `codemap.json`.',
    '',
    '| Feature | Covers | Files | Addresses |',
    '| --- | --- | --- | --- |',
  ];
  for (const name of repo.features) {
    const f = features[name] ?? { files: [], addresses: [] };
    out.push(`| [${name}](#${name}) | ${cell(notes[name])} | ${f.files.length} | ${f.addresses.length} |`);
  }
  for (const name of repo.features) {
    const f = features[name] ?? { files: [], addresses: [] };
    out.push('', `## ${name}`, '');
    if (notes[name]) out.push(notes[name], '');
    if (f.files.length === 0) { out.push('No files carry this feature yet.'); continue; }
    out.push('| File | Lines | Address | What it is |', '| --- | ---: | --- | --- |');
    for (const rel of f.files) {
      const m = maps[rel] ?? {};
      out.push(`| \`${rel}\` | ${m.lines ?? ''} | ${m.address ? `\`${m.address}\`` : ''} | ${cell(m.description)} |`);
    }
  }
  return `${out.join('\n')}\n`;
}
